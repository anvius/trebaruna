package transparency_test

// The licence table embedded in the binary is regenerated from the licence
// files of the modules actually linked, and every one must be free:
//
//	go test ./tests/transparency -run TestEveryLinkedModuleHasAFreeReviewedLicense -update

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
	"testing"

	transparency "codeberg.org/simplicer/trebaruna/src/transparency/infrastructure"
)

var update = flag.Bool("update", false, "regenerate the embedded licence table")

func TestEveryLinkedModuleHasAFreeReviewedLicense(t *testing.T) {
	if _, err := exec.LookPath("go"); err != nil {
		t.Skip("the go toolchain is needed to list the linked modules")
	}
	modules := linkedModules(t)
	if len(modules) == 0 {
		t.Fatal("no modules listed")
	}

	detected := map[string]string{}
	for path, directory := range modules {
		detected[path] = detectLicense(directory)
	}

	if *update {
		writeTable(t, detected)
		return
	}
	for path, license := range detected {
		if license == "unknown" {
			t.Errorf("%s: licence not recognised; read it and add it by hand", path)
			continue
		}
		if !transparency.FreeLicenses[license] {
			t.Errorf("%s carries %s, which is not on the free, AGPL-compatible list", path, license)
		}
		if embedded := transparency.LicenseOf(path); embedded != license {
			t.Errorf("%s: table says %s, licence file says %s; regenerate with -update", path, embedded, license)
		}
	}
}

// linkedModules lists the modules compiled into the CLI and the desktop app,
// with their directories in the module cache.
func linkedModules(t *testing.T) map[string]string {
	t.Helper()
	root := filepath.Join("..", "..")
	command := exec.Command("go", "list", "-tags", "gui", "-deps",
		"-f", "{{with .Module}}{{if not .Main}}{{.Path}}\t{{.Dir}}{{end}}{{end}}",
		"./src/entrypoint/main", "./src/entrypoint/desktop")
	command.Dir = root
	command.Env = append(os.Environ(), "CGO_ENABLED=1")
	output, err := command.Output()
	if err != nil {
		t.Skipf("go list failed (GUI headers missing?): %v", err)
	}
	modules := map[string]string{}
	scanner := bufio.NewScanner(bytes.NewReader(output))
	for scanner.Scan() {
		if path, directory, ok := strings.Cut(scanner.Text(), "\t"); ok {
			modules[path] = directory
		}
	}
	return modules
}

// detectLicense classifies the licence file of a module by its wording.
func detectLicense(directory string) string {
	var text string
	for _, name := range []string{"LICENSE", "LICENSE.txt", "LICENSE.md", "LICENCE", "LICENCE.txt", "COPYING", "COPYING.txt", "LICENSE-APACHE", "LICENSE.MIT"} {
		if content, err := os.ReadFile(filepath.Join(directory, name)); err == nil {
			text = strings.ToLower(string(content))
			break
		}
	}
	normal := strings.Join(strings.Fields(text), " ")
	switch {
	case normal == "":
		return "unknown"
	case strings.Contains(normal, "apache license") && strings.Contains(normal, "version 2.0"):
		return "Apache-2.0"
	case strings.Contains(normal, "mozilla public license") && strings.Contains(normal, "2.0"):
		return "MPL-2.0"
	case strings.Contains(normal, "gnu lesser general public license"):
		return "LGPL-3.0"
	case strings.Contains(normal, "redistribution and use in source and binary forms"):
		if strings.Contains(normal, "neither the name") || strings.Contains(normal, "the names of its contributors") || strings.Contains(normal, "name of the copyright holder") {
			return "BSD-3-Clause"
		}
		return "BSD-2-Clause"
	case strings.Contains(normal, "permission is hereby granted, free of charge"):
		return "MIT"
	case strings.Contains(normal, "permission to use, copy, modify, and/or distribute") || strings.Contains(normal, "isc license"):
		return "ISC"
	case strings.Contains(normal, "this software is provided 'as-is'") && strings.Contains(normal, "altered source versions"):
		return "Zlib"
	case strings.Contains(normal, "this is free and unencumbered software"):
		return "Unlicense"
	}
	return "unknown"
}

func writeTable(t *testing.T, detected map[string]string) {
	t.Helper()
	paths := make([]string, 0, len(detected))
	for path := range detected {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	var source strings.Builder
	source.WriteString("package infrastructure\n\n// Code generated by tests/transparency/licenses_test.go -update; DO NOT EDIT.\n\n")
	source.WriteString("// licenses maps each linked module to the SPDX identifier of its licence file.\nvar licenses = map[string]string{\n")
	for _, path := range paths {
		fmt.Fprintf(&source, "\t%q: %q,\n", path, detected[path])
	}
	source.WriteString("}\n")
	target := filepath.Join("..", "..", "src", "transparency", "infrastructure", "licenses.go")
	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		t.Fatalf("format the table: %v", err)
	}
	if err := os.WriteFile(target, formatted, 0o644); err != nil {
		t.Fatal(err)
	}
}
